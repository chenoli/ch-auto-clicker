import { clampChroma, formatHex, parse } from "culori";

export interface Theme {
  id: string;
  name: string;
  tag: string;
  description: string;
  tokens: Record<string, string>;
}

export interface TokenFile {
  version: number;
  default: string;
  themes: Theme[];
  derived: Record<string, string>;
  shared: Record<string, string>;
}

const HEADER = "GENERATED by tools/gen-tokens from design/tokens.json. Do not edit.";

// Solid colors needed natively (per-state tray icons).
const NATIVE_TOKENS = ["bg", "fg", "fg-3", "accent", "warn", "danger"] as const;

export function toSrgbHex(value: string): string {
  const color = parse(value);
  if (!color) throw new Error(`invalid color: ${value}`);
  return formatHex(clampChroma(color, "oklch")).toUpperCase();
}

function cssBlock(selector: string, vars: Record<string, string>): string {
  const body = Object.entries(vars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
  return `${selector} {\n${body}\n}`;
}

export function buildThemesCss(file: TokenFile): string {
  const blocks = file.themes.map((theme) => {
    const selector = theme.id === file.default ? `:root,\n[data-theme="${theme.id}"]` : `[data-theme="${theme.id}"]`;
    return cssBlock(selector, theme.tokens);
  });
  // Also declared on [data-theme]: custom properties using var() resolve where they are declared, so a
  // nested theme (Tela 07 thumbnails) must recompute them instead of inheriting the :root values.
  const derived = cssBlock(":root,\n[data-theme]", { ...file.derived, ...file.shared });
  return `/* ${HEADER} */\n\n${blocks.join("\n\n")}\n\n/* Derived (all themes) */\n${derived}\n`;
}

export function buildTokensTs(file: TokenFile): string {
  const themes = file.themes.map(({ id, name, tag, description, tokens }) => ({ id, name, tag, description, tokens }));
  const ids = file.themes.map((t) => `"${t.id}"`).join(" | ");
  return `// ${HEADER}

export type ThemeId = ${ids};

export interface ThemeTokens {
  id: ThemeId;
  name: string;
  tag: string;
  description: string;
  tokens: Record<string, string>;
}

export const DEFAULT_THEME: ThemeId = "${file.default}";

export const THEMES: readonly ThemeTokens[] = ${JSON.stringify(themes, null, 2)} as const;
`;
}

function rustIdent(id: string): string {
  return id.toUpperCase().replace(/-/g, "_");
}

export function buildTokensRs(file: TokenFile): string {
  const themes = file.themes
    .map((theme) => {
      const fields = NATIVE_TOKENS.map((key) => {
        const value = theme.tokens[key];
        if (!value) throw new Error(`theme ${theme.id} is missing token ${key}`);
        return `        ${key.replace(/-/g, "_")}: "${toSrgbHex(value)}",`;
      }).join("\n");
      return `pub const ${rustIdent(theme.id)}: NativePalette = NativePalette {\n        id: "${theme.id}",\n${fields}\n    };`;
    })
    .join("\n\n    ");
  const all = file.themes.map((t) => rustIdent(t.id)).join(", ");
  return `// ${HEADER}
//! Theme colors converted to sRGB for native drawing (tray icons).

/// Minimal theme palette as sRGB hex (\`#RRGGBB\`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NativePalette {
    pub id: &'static str,
${NATIVE_TOKENS.map((k) => `    pub ${k.replace(/-/g, "_")}: &'static str,`).join("\n")}
}

#[allow(dead_code)]
pub mod themes {
    use super::NativePalette;

    ${themes}

    pub const ALL: [NativePalette; ${file.themes.length}] = [${all}];
}

pub const DEFAULT_THEME: &str = "${file.default}";
`;
}

export function buildOutputs(file: TokenFile): Record<string, string> {
  return {
    "ui/src/styles/themes.css": buildThemesCss(file),
    "ui/src/styles/tokens.ts": buildTokensTs(file),
    "src-tauri/src/tokens.rs": buildTokensRs(file),
  };
}
